// Command protogen writes package geyserpb from the upstream Yellowstone protos, in pure Go: protocompile parses
// them and protoc-gen-go's own generator writes the code. It fetches the two files at one pinned commit, checks
// their sha256, keeps only the calls the services serve (and the messages they reach), and moves the proto
// packages and file names under carbium so the descriptors never clash with another copy in one binary. The wire is unchanged:
// field numbers and types stay, and the client calls /geyser.Geyser/<Method> by name.
//
// Usage (network on): go run . ../../geyserpb
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/bufbuild/protocompile"
	"google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/known/timestamppb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	repo   = "rpcpool/yellowstone-grpc"
	tag    = "v17.0.2+solana.4.4.1"
	commit = "3c66a659b947e6df09136fc7570bf9918588e2fb"
	goPkg  = "github.com/carbium-sh/carbium-go/stream/geyserpb;geyserpb"
)

// files are the upstream protos (yellowstone-grpc-proto/proto, Apache-2.0) with the sha256 they were read at.
var files = map[string]string{
	"geyser.proto":         "80ee337f361198a0722cb5bdf244fe41838949ab7a3af6d1b182b7fdca9abf02",
	"solana-storage.proto": "e5d16ba9a9e83f6ed8c92a96b6b75dfd64c43f897b976011eb3ec5abe2f3c818",
}

// served are the Geyser calls the services answer; dropped are the upstream calls they do not. Any other call
// fails generation, so a new upstream call is looked at before it is offered.
var (
	served  = []string{"Subscribe", "SubscribeReplayInfo", "Ping", "GetLatestBlockhash", "GetBlockHeight", "GetSlot", "IsBlockhashValid", "GetVersion"}
	dropped = []string{"SubscribeDeshred", "SubscribeGossip"}
	renames = [][2]string{{"geyser", "carbium.geyser"}, {"solana.storage.ConfirmedBlock", "carbium.solana.storage.ConfirmedBlock"}}
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: protogen <out dir>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "protogen:", err)
		os.Exit(1)
	}
}

func fetch(name string) ([]byte, error) {
	url := "https://raw.githubusercontent.com/" + repo + "/" + commit + "/yellowstone-grpc-proto/proto/" + name
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("%s: HTTP %d", name, resp.StatusCode)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(b)
	if got := hex.EncodeToString(sum[:]); got != files[name] {
		return nil, fmt.Errorf("%s: sha256 %s, pinned %s", name, got, files[name])
	}
	return b, nil
}

func run(out string) error {
	src := map[string][]byte{}
	for name := range files {
		b, err := fetch(name)
		if err != nil {
			return err
		}
		src[name] = b
	}
	c := protocompile.Compiler{Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
		Accessor: func(path string) (io.ReadCloser, error) {
			b, ok := src[path]
			if !ok {
				return nil, fmt.Errorf("%s: not an upstream file", path)
			}
			return io.NopCloser(bytes.NewReader(b)), nil
		},
	})}
	compiled, err := c.Compile(context.Background(), "geyser.proto", "solana-storage.proto")
	if err != nil {
		return err
	}
	geyser := protodesc.ToFileDescriptorProto(compiled[0])
	storage := protodesc.ToFileDescriptorProto(compiled[1])
	if err := prune(geyser, storage); err != nil {
		return err
	}
	for _, f := range []*descriptorpb.FileDescriptorProto{geyser, storage} {
		rename(f)
		f.Options.GoPackage = proto.String(goPkg)
		f.Name = proto.String("carbium/" + f.GetName())
		for i, dep := range f.Dependency {
			if _, upstream := files[dep]; upstream {
				f.Dependency[i] = "carbium/" + dep
			}
		}
	}
	req := &pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{"carbium/solana-storage.proto", "carbium/geyser.proto"},
		Parameter:      proto.String("paths=source_relative"),
		ProtoFile:      []*descriptorpb.FileDescriptorProto{protodesc.ToFileDescriptorProto(timestamppb.File_google_protobuf_timestamp_proto), storage, geyser},
	}
	plugin, err := protogen.Options{}.New(req)
	if err != nil {
		return err
	}
	for _, f := range plugin.Files {
		if f.Generate {
			internal_gengo.GenerateFile(plugin, f)
		}
	}
	resp := plugin.Response()
	if resp.Error != nil {
		return fmt.Errorf("%s", resp.GetError())
	}
	for _, f := range resp.File {
		body := "// Generated by stream/internal/protogen from " + repo + " " + tag + " (commit " + commit + "),\n" +
			"// yellowstone-grpc-proto/proto, Apache-2.0: see NOTICE. Calls the services do not serve are removed.\n\n" + f.GetContent()
		if err := os.WriteFile(filepath.Join(out, filepath.Base(f.GetName())), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// prune keeps the served calls and every message and enum they reach, in both files.
func prune(geyser, storage *descriptorpb.FileDescriptorProto) error {
	if len(geyser.Service) != 1 || geyser.Service[0].GetName() != "Geyser" {
		return fmt.Errorf("geyser.proto: want one service Geyser")
	}
	svc := geyser.Service[0]
	var kept []*descriptorpb.MethodDescriptorProto
	reach := []string{}
	for _, m := range svc.Method {
		switch {
		case slices.Contains(served, m.GetName()):
			kept = append(kept, m)
			reach = append(reach, m.GetInputType(), m.GetOutputType())
		case slices.Contains(dropped, m.GetName()):
		default:
			return fmt.Errorf("Geyser.%s is neither served nor dropped: decide before generating", m.GetName())
		}
	}
	if len(kept) != len(served) {
		return fmt.Errorf("upstream offers %d of the %d served calls", len(kept), len(served))
	}
	svc.Method = kept
	type entry struct {
		msg  *descriptorpb.DescriptorProto
		enum bool
	}
	index := map[string]entry{}
	var add func(prefix string, m *descriptorpb.DescriptorProto)
	add = func(prefix string, m *descriptorpb.DescriptorProto) {
		name := prefix + "." + m.GetName()
		index[name] = entry{msg: m}
		for _, n := range m.NestedType {
			add(name, n)
		}
		for _, e := range m.EnumType {
			index[name+"."+e.GetName()] = entry{enum: true}
		}
	}
	for _, f := range []*descriptorpb.FileDescriptorProto{geyser, storage} {
		for _, m := range f.MessageType {
			add("."+f.GetPackage(), m)
		}
		for _, e := range f.EnumType {
			index["."+f.GetPackage()+"."+e.GetName()] = entry{enum: true}
		}
	}
	seen := map[string]bool{}
	for len(reach) > 0 {
		name := reach[0]
		reach = reach[1:]
		if seen[name] {
			continue
		}
		seen[name] = true
		e, ok := index[name]
		if !ok {
			if strings.HasPrefix(name, ".google.protobuf.") {
				continue
			}
			return fmt.Errorf("%s is referenced but not defined", name)
		}
		if e.enum {
			continue
		}
		var walk func(prefix string, m *descriptorpb.DescriptorProto)
		walk = func(prefix string, m *descriptorpb.DescriptorProto) {
			for _, fld := range m.Field {
				if fld.TypeName != nil {
					reach = append(reach, fld.GetTypeName())
				}
			}
			for _, n := range m.NestedType {
				walk(prefix+"."+n.GetName(), n)
				seen[prefix+"."+n.GetName()] = true
			}
		}
		walk(name, e.msg)
		// a nested type keeps its parent
		for parent := name[:strings.LastIndex(name, ".")]; strings.Count(parent, ".") > 1; parent = parent[:strings.LastIndex(parent, ".")] {
			if _, isMsg := index[parent]; isMsg {
				reach = append(reach, parent)
			}
		}
	}
	for _, f := range []*descriptorpb.FileDescriptorProto{geyser, storage} {
		prefix := "." + f.GetPackage() + "."
		f.MessageType = slices.DeleteFunc(f.MessageType, func(m *descriptorpb.DescriptorProto) bool { return !seen[prefix+m.GetName()] })
		f.EnumType = slices.DeleteFunc(f.EnumType, func(e *descriptorpb.EnumDescriptorProto) bool { return !seen[prefix+e.GetName()] })
	}
	return nil
}

// rename moves the proto packages under carbium. in every name and reference.
func rename(f *descriptorpb.FileDescriptorProto) {
	re := func(name string) string {
		for _, r := range renames {
			if name == "."+r[0] || strings.HasPrefix(name, "."+r[0]+".") {
				return "." + r[1] + strings.TrimPrefix(name, "."+r[0])
			}
		}
		return name
	}
	for _, r := range renames {
		if f.GetPackage() == r[0] {
			f.Package = proto.String(r[1])
		}
	}
	var walk func(m *descriptorpb.DescriptorProto)
	walk = func(m *descriptorpb.DescriptorProto) {
		for _, fld := range m.Field {
			if fld.TypeName != nil {
				fld.TypeName = proto.String(re(fld.GetTypeName()))
			}
		}
		for _, n := range m.NestedType {
			walk(n)
		}
	}
	for _, m := range f.MessageType {
		walk(m)
	}
	for _, s := range f.Service {
		for _, m := range s.Method {
			m.InputType = proto.String(re(m.GetInputType()))
			m.OutputType = proto.String(re(m.GetOutputType()))
		}
	}
}
